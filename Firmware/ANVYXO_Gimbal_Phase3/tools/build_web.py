"""Builds web_page.h (gzipped web UI) from web_src/index.html + a coarse mesh of the CAD.

    python tools/build_web.py          # rebuild page (reuses tools/mesh.bin)
    python tools/build_web.py --mesh   # re-tessellate the CAD from ../../gimbal.py first (slow)

The 3D twin uses the same frames as gimbal.py: base parts in table frame, yoke + head in the
tilt-axis frame; posed = head rotX(tilt), then +YOKE_Z, then rotZ(pan).
"""
import base64, gzip, json, os, struct, sys

HERE = os.path.dirname(os.path.abspath(__file__))
SKETCH = os.path.dirname(HERE)
ROOT = os.path.dirname(os.path.dirname(SKETCH))
MESH = os.path.join(HERE, "mesh.bin")
META = os.path.join(HERE, "mesh_meta.json")

COLORS = {  # printed parts match gimbal.py's assembly colours
    "base": (34, 38, 46), "bottom_plate": (34, 38, 46), "yoke": (205, 208, 214), "servo_cap": (40, 44, 52),
    "axle_pin": (40, 44, 52), "head": (215, 218, 224), "head_floor": (40, 44, 52),
    "ESP32S3_CAM": (30, 120, 60), "OLED_096": (20, 30, 90), "laser_12mm": (200, 40, 40), "608ZZ": (170, 170, 180),
    "MG996R_horn": (240, 240, 240), "MG90S_horn": (240, 240, 240), "MG90S": (40, 70, 160), "MG996R": (25, 25, 25),
}
GROUP_ID = {"base": 0, "yoke": 1, "head": 2}


def tessellate():
    sys.path.insert(0, ROOT)
    import gimbal as g
    shapes = {k: (s, g.GROUPS[k]) for k, s in g.parts().items()}
    shapes.update({k: v for k, v in g.vitamins().items() if k in COLORS})
    out, meta = bytearray(), {"parts": [], "yokeZ": g.YOKE_Z, "laser": [0, g.Y_FRONT, g.LASER_Z],
                              "cam": [0, g.Y_FRONT, g.CAM_Z], "panLimit": 90, "tiltLimit": 45}
    for name, (s, grp) in shapes.items():
        verts, tris = s.val().tessellate(0.6, 0.6)
        if len(verts) > 65535:
            raise SystemExit(f"{name}: too many vertices")
        out += struct.pack("<BBBBHI", GROUP_ID[grp], *COLORS[name], len(verts), len(tris))
        for v in verts:
            out += struct.pack("<hhh", *(round(c * 10) for c in (v.x, v.y, v.z)))
        for t in tris:
            out += struct.pack("<HHH", *t)
        meta["parts"].append([name, grp, len(tris)])
        print(f"  {name:20s} {grp:5s} {len(tris):6d} tris")
    open(MESH, "wb").write(out)
    json.dump(meta, open(META, "w"), indent=1)


def main():
    if "--mesh" in sys.argv or not os.path.exists(MESH):
        tessellate()
    meta = json.load(open(META))
    meta.pop("parts")
    html = open(os.path.join(SKETCH, "web_src", "index.html"), encoding="utf-8").read()
    html = html.replace("/*MESH_B64*/", base64.b64encode(open(MESH, "rb").read()).decode())
    html = html.replace("/*MESH_META*/", json.dumps(meta))
    gz = gzip.compress(html.encode("utf-8"), 9, mtime=0)
    rows = ",\n".join(",".join(str(b) for b in gz[i:i + 32]) for i in range(0, len(gz), 32))
    with open(os.path.join(SKETCH, "web_page.h"), "w") as f:
        f.write("// GENERATED by tools/build_web.py from web_src/index.html - do not edit\n#pragma once\n#include <Arduino.h>\n")
        f.write(f"static const size_t INDEX_HTML_GZ_LEN = {len(gz)};\n")
        f.write(f"static const uint8_t INDEX_HTML_GZ[] PROGMEM = {{\n{rows}\n}};\n")
    print(f"web_page.h: html {len(html) / 1024:.0f} KB -> gzip {len(gz) / 1024:.0f} KB")


if __name__ == "__main__":
    main()
